const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

module.exports = async (page, mission, out) => {
  const scene = mission.encounters[0], dialog = page.locator('dialog');
  const move = mode => dialog.locator('.viewpoints').getByRole('button', { name: new RegExp(scene.views.find(v => v.mode === mode).label) }).click();
  await page.locator('.scene-invitation button').click();
  await dialog.locator('.encounter').waitFor();
  await dialog.screenshot({ path: path.join(out, 'encounter-arrival.png') });
  assert.equal(await dialog.locator('.scene-art img').evaluate(el => el.complete && el.naturalWidth > 0), true);
  await dialog.getByRole('button', { name: /Keep an insight/ }).click();
  assert.equal(await dialog.getByRole('button', { name: /Check & record/ }).isDisabled(), true);
  await move('talk');
  const followup = scene.questions.find(q => q.requiresQuestionId);
  const prerequisite = scene.questions.find(q => q.id === followup.requiresQuestionId);
  assert.equal(await dialog.locator('.question-choices').getByRole('button', { name: followup.title, exact: false }).isDisabled(), true);
  await move('listen');
  assert.equal(await dialog.locator('.transcript').innerText(), scene.chapters[0].text);
  assert.equal(await dialog.locator('audio').evaluate(el => el.paused && !el.autoplay), true);
  await dialog.locator('audio').evaluate(el => el.play());
  await page.waitForFunction(() => document.querySelector('dialog audio')?.currentTime > 0.1);
  const oldAudio = await dialog.locator('audio').elementHandle();
  await dialog.screenshot({ path: path.join(out, 'encounter-story-time.png') });
  await move('talk'); assert.equal(await oldAudio.evaluate(el => el.paused), true);
  await dialog.locator('.question-choices').getByRole('button', { name: prerequisite.title, exact: false }).click();
  await dialog.locator('.question-choices').getByRole('button', { name: followup.title, exact: false }).click();
  assert.equal(await dialog.locator('.transcript').innerText(), followup.text);
  await move('object');
  const lens = dialog.getByRole('slider', { name: 'Move the inspection lens' });
  await lens.focus(); await lens.press('Home'); await lens.press('ArrowRight'); assert.equal(await lens.inputValue(), '1');
  await dialog.getByRole('button', { name: new RegExp(scene.object.features[0].label) }).click();
  await dialog.getByRole('button', { name: /Keep an insight/ }).click();
  await dialog.getByLabel('Which reference tests the claim?').selectOption('first-contact');
  await dialog.getByLabel('How does it relate to the claim?').selectOption('supports');
  await dialog.getByRole('button', { name: /Check & record/ }).click();
  await dialog.locator('.check-feedback').waitFor(); assert.equal(await dialog.locator('.insight-success').count(), 0);
  await dialog.getByLabel('Which reference tests the claim?').selectOption(scene.insight.answerEvidenceId);
  await dialog.getByLabel('How does it relate to the claim?').selectOption(scene.insight.relationship);
  await dialog.getByRole('button', { name: /Check & record/ }).click();
  await dialog.locator('.insight-success').waitFor();
  await dialog.screenshot({ path: path.join(out, 'encounter-insight.png') });
  await page.reload(); await dialog.locator('.encounter').waitFor({ timeout: 90000 });
  await dialog.getByRole('button', { name: /Review your insight/ }).click(); await dialog.locator('.insight-success').waitFor();
  await move('listen'); assert.equal(await dialog.locator('audio').evaluate(el => el.paused && !el.autoplay), true);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth), true);
  assert.equal(await dialog.locator('.encounter').evaluate(el => el.scrollWidth <= el.clientWidth), true);
  await dialog.screenshot({ path: path.join(out, 'encounter-mobile.png') });
  await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'hidden' });
  await page.setViewportSize({ width: 1440, height: 1100 });
  // Enter through an inspected painting and return to precisely that workspace.
  await page.locator('.painting-controls button').first().click();
  await dialog.locator('.detail-studies button').first().click();
  const originalHeading = await dialog.locator('#workspace-title').innerText();
  await dialog.getByRole('button', { name: /^Enter the scene/ }).click();
  await dialog.locator('.return-button').click();
  assert.equal(await dialog.locator('#workspace-title').innerText(), originalHeading);
  await dialog.getByRole('button', { name: 'Close workspace' }).click();
  await page.locator('.audit-tools button').click();
  assert.match(await dialog.innerText(), /Source-linked insight recorded/);
  assert.match(await dialog.innerText(), /1 chapters opened · 2 questions asked · 1 observations/);
  await dialog.getByRole('button', { name: /Revisit this scene/ }).click();
  await dialog.locator('.return-button').click();
  await dialog.getByRole('button', { name: 'Close workspace' }).click();
  await page.locator('.dossier-button').click();
  const downloadEvent = page.waitForEvent('download');
  await dialog.getByRole('button', { name: 'Export evidence JSON' }).click();
  const download = await downloadEvent, file = path.join(out, 'encounter-dossier.json'); await download.saveAs(file);
  const dossier = JSON.parse(fs.readFileSync(file, 'utf8'));
  assert.equal(dossier.encounterRecords.length, 1);
  assert.equal(dossier.encounterRecords[0].insight.source.id, 'exchange-origins');
  assert.equal(dossier.encounterRecords[0].state.attempts, 2);
  assert.match(dossier.encounterRecords[0].attribution, /synthesized/i);
  assert.equal(dossier.frauds.length, 0); assert.equal(dossier.finalVault, false);
  const markdownEvent = page.waitForEvent('download');
  await dialog.getByRole('button', { name: /Download dossier/ }).click();
  const markdown = await markdownEvent, markdownFile = path.join(out, 'encounter-dossier.md'); await markdown.saveAs(markdownFile);
  const report = fs.readFileSync(markdownFile, 'utf8');
  assert.match(report, /## Encounter records/); assert.match(report, /Museum audio guide/);
  assert.match(report, /Insight: Insight recorded/); assert.match(report, /Source: \[/);
  await dialog.getByRole('button', { name: 'Close workspace' }).click();
  console.log('PASS: encounter views; real audio playback/pause; gated follow-up; keyboard lens; wrong/right insight; reload without autoplay; return contexts; mobile fit; sourced JSON and Markdown dossier export.');
};
