const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');

function dataModule(relativePath) {
  const module = { exports: {} };
  const code = ts.transpileModule(fs.readFileSync(path.join(root, relativePath), 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  vm.runInNewContext(code, module, { filename: relativePath });
  return module.exports;
}
const contentRoot = 'src/app/projects/calendar-monument/';
const {
  solarCalendarDesign: design,
  solarCalendarStarter: starter,
  solarCalendarChecks: checks,
  solarCalendarSite: settings,
} = dataModule(contentRoot + 'calendar-monument.solar-calendar.ts');
let { solarCalendarObservations: references } = dataModule(
  contentRoot + 'calendar-monument.sample-observations.ts',
);
const { isBlockDesign } = dataModule('src/app/shared/engineering/block-design.ts');
assert.equal(
  isBlockDesign(design),
  true,
  'All stones, holes and targets obey the live builder constraints.',
);
assert.equal(isBlockDesign(starter), true);
assert.equal(starter.targets.length, 0, 'Students locate their own calendar marks.');
assert.equal(starter.blocks.length, 24);
assert.equal(design.blocks.length, 34);
assert.equal(design.blocks.filter((block) => block.aperture?.insert === 'jewel').length, 5);
assert.equal(design.displayObject.model, 'crystal');

const context = { structuredClone };
context.window = context;
vm.createContext(context);
for (const file of [
  'vendor/suncalc.js',
  'vendor/luxon.min.js',
  'geometry.js',
  'solar-day.js',
  'monument-camera.js',
  'optics.js',
  'seasons.js',
  'season-review.js',
]) {
  vm.runInContext(
    fs.readFileSync(path.join(root, 'public/simulations/solar-monument', file), 'utf8'),
    context,
  );
}
const evaluate = (changes = {}) =>
  context.SolarReview.evaluate({
    id: 'solar-calendar-example',
    design,
    checks,
    settings,
    ...changes,
  });
const rows = evaluate();
if (process.argv.includes('--write-references')) {
  references = rows.map(({ settings, measurements }) => ({ settings, measurements }));
  fs.writeFileSync(
    path.join(root, contentRoot, 'calendar-monument.sample-observations.ts'),
    '/** Generated by node scripts/check-solar-calendar.cjs --write-references. */\n' +
      'export const solarCalendarObservations = ' +
      JSON.stringify(references, null, 2) +
      ' as const;\n',
  );
}
assert.deepEqual(
  Array.from(rows, (row) => row.settings.actualValue),
  ['blue light', 'amber light', 'blue light', 'red light'],
);
assert.ok(rows.every((row) => row.settings.outcome === 'met'));
assert.equal(
  JSON.stringify(rows.map(({ settings, measurements }) => ({ settings, measurements }))),
  JSON.stringify(references),
  'The fictional evidence must match the actual solar and optical model, including exact instants and nearby dates.',
);
for (const index of [0, 2]) {
  assert.ok(
    rows[index].measurements
      .filter((m) => m.label.includes('days'))
      .every((m) => m.value.includes('does not match')),
    'The narrow equinox opening distinguishes the tested week-before/week-after dates.',
  );
}
for (const index of [1, 3]) {
  assert.ok(
    rows[index].measurements
      .filter((m) => m.label.includes('days'))
      .every((m) => m.value.includes('also matches')),
    'Solstice matches must not imply exact-day precision.',
  );
}
// Color and alignment must depend on real geometry, not decorative labels or canned pass results.
const sealed = { ...design, blocks: design.blocks.map(({ aperture, ...block }) => block) };
assert.ok(evaluate({ design: sealed }).every((row) => row.settings.outcome === 'missed'));
const open = {
  ...design,
  blocks: design.blocks.map((block) => ({
    ...block,
    ...(block.aperture ? { aperture: { ...block.aperture, insert: 'open' } } : {}),
  })),
};
assert.ok(evaluate({ design: open }).every((row) => row.settings.actualValue === 'sunlight'));
const shifted = {
  ...design,
  targets: design.targets.map((target) => ({ ...target, x: target.x + 0.4 })),
};
assert.ok(evaluate({ design: shifted }).every((row) => row.settings.outcome === 'missed'));
assert.ok(
  evaluate({ settings: { ...settings, latitude: 0 } }).some(
    (row) => row.settings.outcome === 'missed',
  ),
);
for (let index = 0; index < checks.length; index++) {
  const row = rows[index];
  const wrongDate = rows[index === 1 ? 3 : 1];
  const point = design.targets.find((target) => target.id === checks[index].targetId);
  const sun = context.SunCalc.getPosition(
    new Date(wrongDate.settings.utcInstant),
    settings.latitude,
    settings.longitude,
  );
  const value = context.SolarOptics.trace(
    design,
    point,
    context.SolarGeometry.sunDirection(
      (sun.altitude * 180) / Math.PI,
      (sun.azimuth * 180) / Math.PI + 180,
    ),
  ).value;
  assert.notEqual(
    value,
    row.settings.expectedValue,
    'A target must distinguish another seasonal test.',
  );
}
console.log(
  'Solar calendar: valid stone circle, four real colored-light alignments, exact reference evidence, nearby dates, removed jewels, sealed holes, shifted markers and changed location passed.',
);
