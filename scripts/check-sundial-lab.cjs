const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '../public/simulations/solar-monument');
const scope = vm.createContext({ console, structuredClone });
scope.window = scope;
for (const name of ['vendor/suncalc.js', 'vendor/luxon.min.js', 'solar-day.js', 'geometry.js', 'optics.js', 'sundial-lab.js']) vm.runInContext(fs.readFileSync(path.join(root, name), 'utf8'), scope);
const dial = scope.SundialLab;
let design = dial.build({ blocks: [], targets: [] }, 60);
const settings = { latitude: 38.83, longitude: -104.82, zone: 'America/Denver', localDate: '2026-06-21', minutes: 540, observationRule: 'clock' };
const sun = date => { const p = scope.SunCalc.getPosition(date, settings.latitude, settings.longitude); return scope.SolarGeometry.sunDirection(p.altitude * 180 / Math.PI, p.azimuth * 180 / Math.PI + 180); };
const morning = scope.SolarDay.observe(settings, 'clock', 540);
const morningSun = sun(morning.date);
assert.ok(dial.tip(design, morningSun).x < 0, 'A morning Sun in the east casts the tip to the west.');
assert.ok(Math.abs(dial.tip(design, { x: 0, y: Math.SQRT1_2, z: Math.SQRT1_2 }).z + .6) < 1e-12, 'At 45 degrees, shadow length equals post height.');
design = dial.mark(design, morningSun, settings, 'hour', '9 AM');
const fixed = structuredClone(design.targets);
assert.ok(scope.SolarOptics.validDesign(design), 'Observation metadata is accepted by the same solver validator.');
assert.equal(dial.mark(design, morningSun, settings, 'hour', '9 AM').targets.length, 1, 'Re-marking the same minute replaces its old mark.');
assert.throws(() => dial.mark(design, morningSun, { ...settings, localDate: '2026-12-21' }, 'hour', '9 AM'), /marking day/);
assert.throws(() => dial.mark(design, morningSun, { ...settings, latitude: 0 }, 'hour', '9 AM'), /marking day/);
const noonTip = date => dial.tip(design, sun(scope.SolarDay.observe({ ...settings, localDate: date }).date));
const length = p => Math.hypot(p.x, p.z);
assert.ok(length(noonTip('2026-12-21')) > length(noonTip('2026-06-21')) * 5, 'The Colorado winter noon shadow is much longer than summer on the same post.');
assert.deepEqual(structuredClone(design.targets), fixed, 'Observing a different season never moves the original marks.');
assert.deepEqual(dial.build(design, 90).targets, fixed, 'Rebuilding preserves reference marks for comparison.');
for (let i = 1; i < 8; i++) design = dial.mark(design, morningSun, { ...settings, minutes: 540 + i * 30 }, 'hour', 'Time ' + i);
assert.throws(() => dial.mark(design, morningSun, { ...settings, minutes: 999 }, 'hour', 'Extra'), /eight time/);
for (const [kind, localDate] of Object.entries({ march: '2026-03-20', june: '2026-06-21', sept: '2026-09-22', dec: '2026-12-21' })) {
  const observation = scope.SolarDay.observe({ ...settings, localDate });
  design = dial.mark(design, sun(observation.date), { ...settings, localDate, minutes: observation.minutes }, kind, kind);
}
assert.equal(design.targets.length, 12, 'Eight time marks leave room for all four seasonal marks.');
assert.ok(scope.SolarOptics.validDesign(design));
const march = design.targets.find(t => t.settings.markerKind === 'march'), sept = design.targets.find(t => t.settings.markerKind === 'sept');
assert.ok(Math.hypot(march.x - sept.x, march.z - sept.z) < .03, 'Both equinoxes have similar noon tip positions.');
for (const direction of [{ x: 1, y: 0, z: 0 }, { x: 1, y: .00001, z: 0 }]) assert.throws(() => dial.mark(design, direction, settings, 'hour', 'Too low'), /horizon|beyond/);
for (const height of [0, 201, NaN]) assert.throws(() => dial.build(design, height), /height/);
assert.equal(scope.SolarOptics.validDesign({ ...design, targets: [{ ...march, settings: { minutes: Infinity } }] }), false);
assert.throws(() => dial.mark(design, morningSun, { ...settings, localDate: '2026-02-31' }, 'hour', 'Bad date'), /valid place/);
assert.equal(dial.reference({ ...design, targets: [{ ...march, settings: { markerKind: 'hour', localDate: 2026 } }] }), undefined, 'Malformed plugin metadata cannot crash lesson initialization.');
console.log('Sundial: physical tip, seasonal contrast, fixed marks, calibration context, limits, and solver validation passed.');
